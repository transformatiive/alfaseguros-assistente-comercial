import { describe, expect, it } from "vitest";
import {
  ATIVIDADES,
  eventoDaNota,
  eventoDoHistorico,
  lerChamadaRingover,
  linhaDaLead,
  origemDaLead,
  passoDesdeDoHistorico,
  textoDaNota,
} from "./parse.js";

// Texto real de uma nota escrita pela integração Ringover → noCRM (29/10/2026),
// com o número de telefone e o nome trocados.
const NOTA_RINGOVER = `Emitido por Beatriz  Assunção
Duração da chamada : 00:09:18
Gravação de chamadas : https://cdn.ringover.com/records/1-2/abc-27-10-26-11h09-351210270873.mp3
A chamada abordou a proposta de seguro de vida enviada à cliente. A cliente ficou com a intenção de avaliar as propostas, agendando uma nova chamada para a quinta-feira.
Generated by IA. Please verify the information before using it.
Transcrição : https://app.ringover.com/call-logs/9670856693605969453`;

const TENTATIVA_RINGOVER = "Emitido por Beatriz  AssunçãoDuração da chamada : 00:00:00Gravação de chamadas : ";

describe("lerChamadaRingover", () => {
  it("lê duração, gravação e resumo", () => {
    const c = lerChamadaRingover(NOTA_RINGOVER);
    expect(c).not.toBeNull();
    expect(c?.duracaoSeg).toBe(558);
    expect(c?.gravacaoUrl).toBe("https://cdn.ringover.com/records/1-2/abc-27-10-26-11h09-351210270873.mp3");
    expect(c?.resumo).toMatch(/^A chamada abordou/);
    expect(c?.resumo).not.toMatch(/Generated by/);
  });

  it("uma tentativa sem conversa vem com 0 segundos e sem gravação", () => {
    const c = lerChamadaRingover(TENTATIVA_RINGOVER);
    expect(c).toEqual({ duracaoSeg: 0, gravacaoUrl: null, resumo: null });
  });

  it("devolve null para uma nota escrita à mão", () => {
    expect(lerChamadaRingover("Não atende. Mensagem enviada no WhatsApp.")).toBeNull();
    expect(lerChamadaRingover("")).toBeNull();
  });

  it("aceita horas com um dígito", () => {
    expect(lerChamadaRingover("Duração da chamada : 1:02:03")?.duracaoSeg).toBe(3723);
  });
});

describe("textoDaNota", () => {
  it("prefere raw_content", () => {
    expect(textoDaNota({ raw_content: "olá", content: "<p>outro</p>" })).toBe("olá");
  });
  it("tira o HTML de content quando não há raw_content", () => {
    expect(textoDaNota({ raw_content: null, content: "Linha 1<br>Linha&nbsp;2 &amp; <b>3</b>" })).toBe("Linha 1\nLinha 2 & 3");
  });
  it("não rebenta sem texto nenhum", () => {
    expect(textoDaNota({ raw_content: null, content: null })).toBe("");
  });
});

describe("eventoDaNota", () => {
  const base = { id: 7, created_at: "2026-10-27T11:19:21.000Z", user: { id: 246015 } };

  it("uma nota do Ringover é uma chamada, mesmo marcada como 'Atendida'", () => {
    const e = eventoDaNota(10, { ...base, raw_content: TENTATIVA_RINGOVER, activity_id: ATIVIDADES.atendida });
    expect(e.tipo).toBe("chamada");
    expect(e.duracaoSeg).toBe(0);
    expect(e.id).toBe("c:7");
    expect(e.userId).toBe(246015);
  });

  it("'Não atendida' sem texto do Ringover conta como tentativa", () => {
    const e = eventoDaNota(10, { ...base, raw_content: "não atende", activity_id: ATIVIDADES.naoAtendida });
    expect(e).toMatchObject({ tipo: "chamada", duracaoSeg: 0 });
  });

  it("chamada registada à mão fica sem duração", () => {
    const e = eventoDaNota(10, { ...base, raw_content: "falei com a cliente", activity_id: ATIVIDADES.atendida });
    expect(e).toMatchObject({ tipo: "chamada", duracaoSeg: null });
  });

  it("email e nota livre", () => {
    expect(eventoDaNota(10, { ...base, raw_content: "", activity_id: ATIVIDADES.email }).tipo).toBe("email");
    const nota = eventoDaNota(10, { ...base, raw_content: "Ligar 5ªf às 11h00", activity_id: null });
    expect(nota).toMatchObject({ tipo: "nota", texto: "Ligar 5ªf às 11h00" });
  });

  it("nota vazia fica com texto null e sem user", () => {
    const e = eventoDaNota(10, { id: 8, created_at: base.created_at, raw_content: "   ", user: null });
    expect(e.texto).toBeNull();
    expect(e.userId).toBeNull();
  });

  it("corta textos muito longos", () => {
    const e = eventoDaNota(10, { ...base, raw_content: "x".repeat(5000) });
    expect(e.texto?.length).toBe(2000);
  });
});

describe("eventoDoHistorico", () => {
  it("traduz mudanças de passo e estado", () => {
    const p = eventoDoHistorico(1, { id: 3, action_type: "step_changed", action_item: { name: "Simulação enviada" }, created_at: "2026-10-26T17:43:38.000Z", user: { id: 9 } });
    expect(p).toMatchObject({ id: "h:3", tipo: "passo", valor: "Simulação enviada", userId: 9 });
    const s = eventoDoHistorico(1, { id: 4, action_type: "status_changed", action_item: { name: "standby" }, created_at: "2026-10-26T17:43:38.000Z" });
    expect(s).toMatchObject({ tipo: "estado", valor: "standby", userId: null });
  });

  it("ignora comment_added e tipos desconhecidos", () => {
    expect(eventoDoHistorico(1, { id: 5, action_type: "comment_added", created_at: "2026-10-26T00:00:00Z" })).toBeNull();
    expect(eventoDoHistorico(1, { id: 6, action_type: "amount_set", created_at: "2026-10-26T00:00:00Z" })).toBeNull();
  });
});

describe("passoDesdeDoHistorico", () => {
  it("usa a última mudança de passo", () => {
    const d = passoDesdeDoHistorico([
      { id: 1, action_type: "lead_created", created_at: "2026-10-01T10:00:00Z" },
      { id: 2, action_type: "step_changed", created_at: "2026-10-10T10:00:00Z" },
      { id: 3, action_type: "step_changed", created_at: "2026-10-05T10:00:00Z" },
    ]);
    expect(d?.toISOString()).toBe("2026-10-10T10:00:00.000Z");
  });
  it("cai na criação quando nunca mudou de passo", () => {
    const d = passoDesdeDoHistorico([{ id: 1, action_type: "lead_created", created_at: "2026-10-01T10:00:00Z" }]);
    expect(d?.toISOString()).toBe("2026-10-01T10:00:00.000Z");
  });
  it("null sem histórico útil", () => {
    expect(passoDesdeDoHistorico([])).toBeNull();
  });
});

describe("linhaDaLead e origem", () => {
  const cats = new Map<string, string | null>([
    ["Site", "Origem da Lead"],
    ["SCME-ERICEIRA", "Protocolos"],
    ["Must", "Parcerias"],
    ["Preço", "Motivo Perdido"],
  ]);

  it("pasta de cliente ganha", () => {
    expect(origemDaLead({ client_folder_name: "ADSGY", tags: ["Site"] }, cats)).toBe("ADSGY");
  });
  it("depois a etiqueta de origem, protocolo ou parceria", () => {
    expect(origemDaLead({ client_folder_name: null, tags: ["Preço", "Site"] }, cats)).toBe("Site");
    expect(origemDaLead({ tags: ["SCME-ERICEIRA"] }, cats)).toBe("SCME-ERICEIRA");
    expect(origemDaLead({ tags: ["Must"] }, cats)).toBe("Parcerias");
    expect(origemDaLead({ tags: ["Preço"] }, cats)).toBeNull();
  });

  it("converte uma lead real", () => {
    const r = linhaDaLead(
      {
        id: 39936359,
        title: "ana ana - ADSGY",
        step: "Simulação enviada",
        step_id: 67548,
        status: "todo",
        amount: 230.41,
        user_id: 246015,
        tags: ["ADSGY"],
        client_folder_name: "ADSGY",
        created_at: "2026-10-22T14:33:02.000Z",
        updated_at: "2026-10-29T11:07:30.000Z",
        closed_at: null,
        next_action_at: "2026-10-29T11:00:00.000Z",
        remind_date: "2026-10-29",
        remind_time: "11:00",
      },
      cats,
    );
    expect(r).toMatchObject({ id: 39936359, passo: "Simulação enviada", estado: "todo", valor: 230.41, userId: 246015, origem: "ADSGY", proximaAcaoDia: "2026-10-29", proximaAcaoHora: "11:00", fechadaEm: null });
  });

  it("título vazio e data de lembrete inválida", () => {
    const r = linhaDaLead({ id: 1, title: "  ", status: "standby", created_at: "2026-10-01T00:00:00Z", updated_at: "2026-10-01T00:00:00Z", remind_date: "amanhã" }, cats);
    expect(r.titulo).toBe("Lead 1");
    expect(r.proximaAcaoDia).toBeNull();
    expect(r.userId).toBeNull();
  });
});
