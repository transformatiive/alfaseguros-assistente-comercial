import type { NocrmApiComment, NocrmApiHistory, NocrmApiLead } from "./types.js";

/**
 * Tradução das respostas do noCRM para as linhas que guardamos.
 * Funções puras: sem rede, sem base de dados, testadas em `parse.test.ts`.
 */

/** Actividades da conta alfa-seguros (GET /activities, 29/10/2026). */
export const ATIVIDADES = {
  ligar: 91596,
  atendida: 91597,
  naoAtendida: 91598,
  email: 91599,
  emailRecebido: 362265,
  reuniao: 91600,
} as const;

export type TipoEvento = "chamada" | "nota" | "email" | "passo" | "estado" | "dono" | "criada" | "outro";

export interface EventoParsed {
  id: string;
  leadId: number;
  tipo: TipoEvento;
  userId: number | null;
  ocorreuEm: Date;
  duracaoSeg: number | null;
  valor: string | null;
  texto: string | null;
  gravacaoUrl: string | null;
}

const TEXTO_MAX = 2000;

function cortar(s: string | null): string | null {
  if (s == null) return null;
  const t = s.trim();
  if (!t) return null;
  return t.length > TEXTO_MAX ? `${t.slice(0, TEXTO_MAX - 1)}…` : t;
}

/** Texto da nota sem HTML. O noCRM manda `raw_content` em texto e `content` em HTML. */
export function textoDaNota(c: Pick<NocrmApiComment, "raw_content" | "content">): string {
  if (c.raw_content && c.raw_content.trim()) return c.raw_content;
  return (c.content ?? "")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&");
}

export interface ChamadaRingover {
  duracaoSeg: number;
  gravacaoUrl: string | null;
  resumo: string | null;
}

/**
 * Lê uma nota escrita pela integração Ringover → noCRM. Formato real:
 *
 *   Emitido por Beatriz  Assunção
 *   Duração da chamada : 00:09:18
 *   Gravação de chamadas : https://cdn.ringover.com/records/....mp3
 *   A chamada abordou ...            ← resumo da IA do Ringover (nem sempre)
 *   Generated by IA. Please verify ...
 *   Transcrição : https://app.ringover.com/call-logs/...
 *
 * Devolve null quando a nota não é do Ringover.
 */
export function lerChamadaRingover(texto: string): ChamadaRingover | null {
  const dur = texto.match(/Dura[çc][ãa]o da chamada\s*:\s*(\d{1,2}):(\d{2}):(\d{2})/i);
  if (!dur) return null;
  const duracaoSeg = Number(dur[1]) * 3600 + Number(dur[2]) * 60 + Number(dur[3]);
  const grav = texto.match(/Grava[çc](?:[ãa]o|[õo]es) de chamadas\s*:\s*(https?:\/\/\S+)/i);
  const gravacaoUrl = grav ? grav[1] : null;

  let resumo: string | null = null;
  if (grav) {
    const depois = texto.slice((grav.index ?? 0) + grav[0].length);
    const fim = depois.search(/Generated by|Transcri[çc][ãa]o\s*:/i);
    resumo = cortar(fim >= 0 ? depois.slice(0, fim) : depois);
  }
  return { duracaoSeg, gravacaoUrl, resumo };
}

export function eventoDaNota(leadId: number, c: NocrmApiComment): EventoParsed {
  const texto = textoDaNota(c);
  const base = {
    id: `c:${c.id}`,
    leadId,
    userId: c.user?.id ?? null,
    ocorreuEm: new Date(c.created_at),
    valor: null,
  };
  const ring = lerChamadaRingover(texto);
  if (ring) {
    return { ...base, tipo: "chamada", duracaoSeg: ring.duracaoSeg, gravacaoUrl: ring.gravacaoUrl, texto: ring.resumo };
  }
  const act = c.activity_id ?? null;
  if (act === ATIVIDADES.naoAtendida) {
    return { ...base, tipo: "chamada", duracaoSeg: 0, gravacaoUrl: null, texto: cortar(texto) };
  }
  if (act === ATIVIDADES.atendida || act === ATIVIDADES.ligar) {
    // Chamada registada à mão, sem duração.
    return { ...base, tipo: "chamada", duracaoSeg: null, gravacaoUrl: null, texto: cortar(texto) };
  }
  if (act === ATIVIDADES.email || act === ATIVIDADES.emailRecebido) {
    return { ...base, tipo: "email", duracaoSeg: null, gravacaoUrl: null, texto: cortar(texto) };
  }
  return { ...base, tipo: "nota", duracaoSeg: null, gravacaoUrl: null, texto: cortar(texto) };
}

const TIPO_HISTORICO: Record<string, TipoEvento | undefined> = {
  step_changed: "passo",
  status_changed: "estado",
  user_assigned: "dono",
  lead_created: "criada",
  email_sent: "email",
};

/** Eventos do histórico que interessam. `comment_added` já vem pelas notas. */
export function eventoDoHistorico(leadId: number, h: NocrmApiHistory): EventoParsed | null {
  const tipo = TIPO_HISTORICO[h.action_type];
  if (!tipo) return null;
  const nome = h.action_item?.name ?? null;
  return {
    id: `h:${h.id}`,
    leadId,
    tipo,
    userId: h.user?.id ?? null,
    ocorreuEm: new Date(h.created_at),
    duracaoSeg: null,
    valor: tipo === "passo" || tipo === "estado" ? nome : null,
    texto: tipo === "dono" ? nome : null,
    gravacaoUrl: null,
  };
}

/** Quando a lead entrou no passo actual: a última mudança de passo, ou a criação. */
export function passoDesdeDoHistorico(historico: NocrmApiHistory[]): Date | null {
  let melhor: Date | null = null;
  for (const h of historico) {
    if (h.action_type !== "step_changed" && h.action_type !== "lead_created") continue;
    const d = new Date(h.created_at);
    if (Number.isNaN(d.getTime())) continue;
    if (h.action_type === "lead_created" && melhor) continue;
    if (!melhor || (h.action_type === "step_changed" && d > melhor)) melhor = d;
  }
  return melhor;
}

export interface LeadRow {
  id: number;
  titulo: string;
  passo: string | null;
  passoId: number | null;
  estado: string;
  valor: number | null;
  userId: number | null;
  origem: string | null;
  tags: string[];
  criadaEm: Date;
  atualizadaEm: Date;
  fechadaEm: Date | null;
  proximaAcaoEm: Date | null;
  proximaAcaoDia: string | null;
  proximaAcaoHora: string | null;
}

/**
 * A origem da lead: a pasta de cliente quando existe (ADSGY, LTW, ...), senão
 * a primeira etiqueta da categoria "Origem da Lead", senão a primeira de
 * "Protocolos" ou "Parcerias".
 */
export function origemDaLead(lead: Pick<NocrmApiLead, "client_folder_name" | "tags">, categoriaDe: Map<string, string | null>): string | null {
  if (lead.client_folder_name && lead.client_folder_name.trim()) return lead.client_folder_name.trim();
  const tags = lead.tags ?? [];
  for (const cat of ["Origem da Lead", "Protocolos", "Parcerias", "Parcerias BETA", "Parcerias GAMMA"]) {
    const t = tags.find((x) => categoriaDe.get(x) === cat);
    if (t) return cat.startsWith("Parcerias") ? "Parcerias" : t;
  }
  return null;
}

const DIA_RE = /^\d{4}-\d{2}-\d{2}$/;

export function linhaDaLead(l: NocrmApiLead, categoriaDe: Map<string, string | null>): LeadRow {
  return {
    id: l.id,
    titulo: (l.title ?? "").trim() || `Lead ${l.id}`,
    passo: l.step ?? null,
    passoId: l.step_id ?? null,
    estado: l.status,
    valor: l.amount ?? null,
    userId: l.user_id ?? null,
    origem: origemDaLead(l, categoriaDe),
    tags: l.tags ?? [],
    criadaEm: new Date(l.created_at),
    atualizadaEm: new Date(l.updated_at),
    fechadaEm: l.closed_at ? new Date(l.closed_at) : null,
    proximaAcaoEm: l.next_action_at ? new Date(l.next_action_at) : null,
    proximaAcaoDia: l.remind_date && DIA_RE.test(l.remind_date) ? l.remind_date : null,
    proximaAcaoHora: l.remind_time ?? null,
  };
}

export function nomeDoUser(u: { firstname?: string | null; lastname?: string | null; email?: string | null; id: number }): string {
  const n = [u.firstname, u.lastname].filter((x) => x && x.trim()).join(" ").trim();
  return n || u.email || `Utilizador ${u.id}`;
}
